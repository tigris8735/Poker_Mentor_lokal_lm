import random

class OfflineAIService:
    """Оффлайн-заглушка для AI когда LM Studio недоступен"""
    
    def __init__(self):
        self.advice_responses = [
            "💡 Играйте тайтово-агрессивно, особенно в ранней позиции.",
            "🎯 Обращайте внимание на позицию за столом - это ключевой фактор.",
            "💰 Управляйте размером банка - не инвестируйте слишком много со средними руками.",
            "👀 Наблюдайте за оппонентами и адаптируйте свою стратегию.",
            "🃏 Избегайте играть слишком много рук на префлопе.",
            "🛡️ Используйте контбеты для защиты своей позиции.",
            "🧮 Помните о математике покера - считайте оддсы.",
            "🎭 Развивайте навыки чтения оппонентов.",
            "🏦 Управляйте своим банкроллом - не рискуйте больше 5% за одну сессию.",
            "📊 Анализируйте свои раздачи после игры."
        ]
        
        self.analysis_responses = [
            "📈 На префлопе учитывайте позицию и силу руки.",
            "🔄 На постфлопе анализируйте текстуру борда и диапазоны оппонентов.",
            "⚖️ Балансируйте между валью и блефом.",
            "🎪 Учитывайте игровые тенденции оппонентов.",
            "💎 Сфокусируйтесь на фундаментальной стратегии."
        ]
    
    def get_advice(self, situation: str) -> str:
        advice = random.choice(self.advice_responses)
        return f"{advice}\n\n🤖 *Примечание: AI временно недоступен, используем общие советы*"
    
    def analyze_hand(self, hand_data: str) -> str:
        analysis = random.choice(self.analysis_responses)
        return f"🔍 {analysis}\n\n📝 *Ваша раздача:* {hand_data}\n\n🤖 *Примечание: AI временно недоступен*"